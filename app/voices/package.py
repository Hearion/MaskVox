"""Validate and unpack untrusted voice archives."""

from __future__ import annotations

import json
import re
import stat
from collections.abc import Callable
from difflib import SequenceMatcher
from pathlib import Path, PurePosixPath
from zipfile import BadZipFile, ZIP_STORED, ZipFile, ZipInfo

CHAR_LIMIT = 80
MAX_BYTES = 2 * 1024**3
MAX_FILES = 512
NAMES = {"model.onnx", "model.index", "meta.json"}
VOICE_INPUTS = {"phone", "phone_lengths", "pitch", "pitchf", "ds", "rnd"}


class VoiceError(ValueError):
    """A user-facing voice package error."""


def verify_model(path: Path) -> dict[str, int | str]:
    import onnx
    from google.protobuf.descriptor import FieldDescriptor

    if not path.is_file() or not 0 < path.stat().st_size <= MAX_BYTES:
        raise VoiceError("音色模型缺失或大小超过限制。")
    try:
        model = onnx.load_model(path, load_external_data=False)
    except Exception as exc:
        raise VoiceError("无法读取 ONNX 音色模型，文件可能已损坏。") from exc

    pending = [model]
    while pending:
        message = pending.pop()
        if isinstance(message, onnx.TensorProto):
            if message.data_location == onnx.TensorProto.EXTERNAL or message.external_data:
                raise VoiceError("音色模型引用了外部数据文件，已拒绝导入。")
            continue
        for field, value in message.ListFields():
            if field.type == FieldDescriptor.TYPE_MESSAGE:
                if field.is_repeated:
                    pending.extend(value)
                else:
                    pending.append(value)

    meta = {entry.key: entry.value for entry in model.metadata_props}
    if meta.get("mv_format") != "1":
        raise VoiceError("该 ONNX 音色不是受支持的 MaskVox 格式。")
    try:
        version = meta["version"]
        sr, dim, f0 = int(meta["sr"]), int(meta["vec_dim"]), int(meta["f0"])
        if dim != {"v1": 256, "v2": 768}[version] or sr not in {32000, 40000, 48000} or f0 != 1:
            raise ValueError
    except (KeyError, ValueError) as exc:
        raise VoiceError("音色模型的版本、采样率或音高元数据无效。") from exc
    if {value.name for value in model.graph.input} not in (VOICE_INPUTS, VOICE_INPUTS | {"source_noise"}) or {
        value.name for value in model.graph.output
    } != {"audio"}:
        raise VoiceError("音色模型的输入或输出不符合 MaskVox 格式。")
    try:
        onnx.checker.check_model(model)
    except Exception as exc:
        raise VoiceError("音色 ONNX 模型校验失败。") from exc
    return {"version": version, "sr": sr, "vec_dim": dim, "f0": f0}


def archive_entries(archive: ZipFile) -> list[ZipInfo]:
    entries = archive.infolist()
    if len(entries) > MAX_FILES or sum(entry.file_size for entry in entries) > MAX_BYTES:
        raise VoiceError("压缩包超过上限（512 个项目或解压后 2 GB）。")
    seen: set[str] = set()
    items = []
    for entry in entries:
        name = entry.orig_filename
        parts = name.rstrip("/").split("/")
        if (
            "\\" in name
            or ":" in name
            or any(part in {"", ".", ".."} or any(ord(c) < 32 for c in part) for part in parts)
            or stat.S_ISLNK(entry.external_attr >> 16)
            or entry.flag_bits & 1
        ):
            raise VoiceError("压缩包含有不安全的路径、链接或加密文件。")
        key = name.rstrip("/").casefold()
        if key in seen:
            raise VoiceError("压缩包中有重复文件或目录。")
        seen.add(key)
        if not entry.is_dir():
            items.append(entry)
    return items


def _extract(archive: ZipFile, entry: ZipInfo, target: Path, check: Callable[[], None] | None) -> None:
    # Targets are generated by MaskVox and never use a ZIP entry as a disk path.
    with archive.open(entry) as source, target.open("xb") as out:
        count = 0
        while chunk := source.read(1024 * 1024):
            if check is not None:
                check()
            count += len(chunk)
            if count > entry.file_size or count > MAX_BYTES:
                raise VoiceError("压缩包解压大小异常。")
            out.write(chunk)
        if count != entry.file_size:
            raise VoiceError("压缩包内容不完整。")


def unpack_package(path: Path, out: Path, check: Callable[[], None] | None = None) -> dict:
    try:
        with ZipFile(path) as archive:
            entries = archive_entries(archive)
            files = {item.filename: item for item in entries}
            if len(archive.infolist()) != len(entries) or not {
                "model.onnx", "meta.json"
            } <= files.keys() <= NAMES:
                raise VoiceError("音色包需要 model.onnx、meta.json 和可选的 model.index。")
            if files["meta.json"].file_size > 65_536:
                raise VoiceError("音色包的元数据超过大小限制。")
            data = json.loads(archive.read("meta.json"))
            if not isinstance(data, dict) or not isinstance(data.get("name"), str):
                raise VoiceError("音色包缺少有效的名称。")
            for key in ("model.onnx", "model.index"):
                if key in files:
                    _extract(archive, files[key], out / key, check)
    except (BadZipFile, UnicodeError, json.JSONDecodeError, NotImplementedError) as exc:
        raise VoiceError("音色包已损坏或使用了不支持的压缩格式。") from exc
    result = verify_model(out / "model.onnx")
    attribution = data.get("attribution")
    if isinstance(attribution, dict) and all(isinstance(value, str) for value in attribution.values()):
        result["attribution"] = attribution
    return {**result, "name": data["name"]}


def unpack_rvc(path: Path, out: Path, check: Callable[[], None] | None = None) -> tuple[list[tuple[str, Path]], list[tuple[str, Path]]]:
    weights: list[tuple[str, Path]] = []
    indexes: list[tuple[str, Path]] = []
    try:
        with ZipFile(path) as archive:
            for number, item in enumerate(archive_entries(archive)):
                original = PurePosixPath(item.filename)
                suffix = original.suffix.lower()
                if suffix not in {".pth", ".index"} or "__MACOSX" in original.parts or original.name.startswith("._"):
                    continue
                dest = out / f"{number}{suffix}"
                _extract(archive, item, dest, check)
                (weights if suffix == ".pth" else indexes).append((original.name, dest))
    except (BadZipFile, NotImplementedError) as exc:
        raise VoiceError("压缩包已损坏或使用了不支持的压缩格式。") from exc
    if not weights:
        raise VoiceError("压缩包里没有 .pth 音色文件。")
    return weights, indexes


def match_index(name: str, indexes: list[tuple[str, Path]]) -> Path | None:
    stem = Path(name).stem.casefold()
    normalized = re.sub(r"[\W_]+", "", stem)
    matches: list[tuple[bool, float, Path]] = []
    for filename, path in indexes:
        other = Path(filename).stem.casefold()
        added = other.startswith("added_")
        tail = re.sub(r"^(added|trained)_ivf\d+_flat_nprobe_\d+_", "", other)
        tail = re.sub(r"_v[12]$", "", tail)
        tail = re.sub(r"[\W_]+", "", tail)
        if normalized and tail:
            ratio = SequenceMatcher(None, normalized, tail).ratio()
            if normalized in tail and len(normalized) >= 3:
                ratio = 1.0
            if ratio >= 0.65:
                matches.append((added, ratio, path))
    return max(matches, default=(False, 0, None), key=lambda match: match[:2])[2]


def write_package(source: Path, destination: Path) -> None:
    import tempfile

    with tempfile.NamedTemporaryFile(dir=destination.parent, suffix=".tmp", delete=False) as file:
        temp = Path(file.name)
    try:
        with ZipFile(temp, "w", ZIP_STORED) as archive:
            for name in sorted(NAMES):
                path = source / name
                if name != "model.index" or path.is_file():
                    archive.write(path, arcname=name)
        temp.replace(destination)
    finally:
        temp.unlink(missing_ok=True)
